// Builds each variant of the composite Worker with the same rolldown build and options.
// Writes <dist>/<variant>/worker.mjs and results/builds.json.
// BENCH_DIST=<folder> writes the bundles to that folder (default: dist) and the summary to
// results/builds-<folder>.json, so a build of a change does not overwrite the baseline in dist/.
// BENCH_VARIANTS=<name,name> builds only those variants.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';
import { ROLLDOWN_DIST, ROLLDOWN_VERSION, ROOT, VARIANTS, rolldown, rolldownInputOptions, rolldownOutputOptions } from './config.mjs';

if (!ROLLDOWN_DIST) throw new Error('Set ROLLDOWN_DIST to the packages/rolldown/dist folder of a rolldown checkout (see README.md).');

const DIST = process.env.BENCH_DIST ?? 'dist';
const ONLY = process.env.BENCH_VARIANTS?.split(',');
const template = readFileSync(join(ROOT, 'app/main.template.js'), 'utf8');
const builds = {};
for (const [name, v] of Object.entries(VARIANTS).filter(([name]) => !ONLY || ONLY.includes(name))) {
  const entry = join(ROOT, `app/main.${v.phase ? 'defer' : 'eager'}.js`);
  writeFileSync(entry, '// Generated by scripts/build.mjs from main.template.js. Do not edit.\n' + template.replaceAll('__PHASE__', v.phase));
  const logs = [];
  const t0 = performance.now();
  const bundle = await rolldown(rolldownInputOptions(entry, logs, v.extra));
  const { output } = await bundle.generate(rolldownOutputOptions(v.minify));
  await bundle.close();
  const buildMs = performance.now() - t0;
  const chunks = output.filter((o) => o.type === 'chunk');
  if (chunks.length !== 1) throw new Error(`${name}: expected 1 chunk, got ${chunks.length}`);
  const [chunk] = chunks;
  mkdirSync(join(ROOT, DIST, name), { recursive: true });
  writeFileSync(join(ROOT, DIST, name, 'worker.mjs'), chunk.code);
  const logCodes = {};
  for (const l of logs) logCodes[l.code] = (logCodes[l.code] ?? 0) + 1;
  builds[name] = {
    file: `${DIST}/${name}/worker.mjs`,
    buildMs: Math.round(buildMs),
    bytes: Buffer.byteLength(chunk.code),
    gzipBytes: gzipSync(chunk.code).length,
    sha1: createHash('sha1').update(chunk.code).digest('hex'),
    moduleCount: Object.keys(chunk.modules).length,
    modules: Object.keys(chunk.modules).map((id) => id.replace(ROOT + '/', '')).sort(),
    imports: chunk.imports,
    logCodes,
    eagerExternalWarnings: logs.filter((l) => l.code === 'DEFERRED_EXTERNAL_EVALUATED_EAGERLY').map((l) => l.message),
    otherLogs: logs.filter((l) => l.code !== 'DEFERRED_EXTERNAL_EVALUATED_EAGERLY').slice(0, 20),
    importDeferSyntaxLeft: /\bimport\s+defer\b|import\.defer\s*\(/.test(chunk.code),
  };
}

const diff = (a, b) => a.filter((m) => !new Set(b).has(m));
const moduleSetDiff = builds.eager && builds.defer
  ? { onlyEager: diff(builds.eager.modules, builds.defer.modules), onlyDefer: diff(builds.defer.modules, builds.eager.modules) }
  : null;
const worktree = join(ROLLDOWN_DIST, '../../..');
const git = (...a) => execFileSync('git', ['-C', worktree, ...a], { encoding: 'utf8' }).trim();
const meta = {
  date: new Date().toISOString(),
  rolldownVersion: ROLLDOWN_VERSION,
  rolldownDist: ROLLDOWN_DIST,
  rolldownHead: git('log', '-1', '--format=%h %s'),
  rolldownBranch: git('branch', '--show-current'),
  rolldownDirtyFiles: git('status', '--porcelain').split('\n').filter(Boolean).length,
  node: process.version,
  dist: DIST,
};
writeFileSync(join(ROOT, DIST === 'dist' ? 'results/builds.json' : `results/builds-${DIST}.json`), JSON.stringify({ meta, builds, moduleSetDiff }, null, 1));
console.log(JSON.stringify(meta));
for (const [name, b] of Object.entries(builds)) {
  console.log(`${name.padEnd(13)} ${String(b.bytes).padStart(9)} B  gzip ${String(b.gzipBytes).padStart(8)} B  modules ${b.moduleCount}  build ${b.buildMs} ms  sha1 ${b.sha1.slice(0, 12)}  imports ${b.imports.join(',') || '-'}  logs ${JSON.stringify(b.logCodes)}  importDeferLeft=${b.importDeferSyntaxLeft}`);
}
if (moduleSetDiff) console.log('module set diff (eager vs defer):', JSON.stringify({ onlyEager: moduleSetDiff.onlyEager.length, onlyDefer: moduleSetDiff.onlyDefer.length }));
